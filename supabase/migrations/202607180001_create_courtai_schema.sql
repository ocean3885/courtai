CREATE SCHEMA IF NOT EXISTS courtai;

CREATE TABLE IF NOT EXISTS courtai.users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT UNIQUE NOT NULL,
  password TEXT NOT NULL,
  name TEXT,
  role TEXT DEFAULT 'USER',
  is_active INTEGER DEFAULT 1,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS courtai.prompts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES courtai.users(id),
  name TEXT NOT NULL,
  prompt TEXT NOT NULL,
  model TEXT NOT NULL,
  category TEXT,
  is_favorite INTEGER DEFAULT 0,
  usage_count INTEGER DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS courtai.repayment_plan_templates (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES courtai.users(id),
  name TEXT NOT NULL,
  creditors TEXT NOT NULL,
  monthly_available INTEGER NOT NULL,
  months INTEGER NOT NULL,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS courtai.creditor (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES courtai.users(id),
  title TEXT NOT NULL,
  data TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS courtai.case_documents (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  creditor_id INTEGER NOT NULL REFERENCES courtai.creditor(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  source_snapshot TEXT NOT NULL,
  changes TEXT DEFAULT '',
  html_preview TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS courtai.standard_median_income (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  year INTEGER NOT NULL,
  household_size INTEGER NOT NULL,
  amount INTEGER NOT NULL,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(year, household_size)
);

CREATE TABLE IF NOT EXISTS courtai.inquiries (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER REFERENCES courtai.users(id),
  title TEXT NOT NULL,
  content TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS prompts_user_updated_idx
  ON courtai.prompts (user_id, updated_at DESC);

CREATE INDEX IF NOT EXISTS repayment_plan_templates_user_created_idx
  ON courtai.repayment_plan_templates (user_id, created_at DESC);

CREATE INDEX IF NOT EXISTS creditor_user_updated_idx
  ON courtai.creditor (user_id, updated_at DESC);

CREATE INDEX IF NOT EXISTS case_documents_creditor_created_idx
  ON courtai.case_documents (creditor_id, created_at DESC);

CREATE INDEX IF NOT EXISTS inquiries_created_idx
  ON courtai.inquiries (created_at DESC);
