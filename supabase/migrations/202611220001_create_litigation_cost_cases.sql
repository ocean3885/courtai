CREATE TABLE IF NOT EXISTS courtai.litigation_cost_cases (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES courtai.users(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  court TEXT NOT NULL DEFAULT '',
  case_number TEXT NOT NULL DEFAULT '',
  application_date TEXT NOT NULL DEFAULT '',
  data JSONB NOT NULL,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS litigation_cost_cases_user_updated_idx
  ON courtai.litigation_cost_cases (user_id, updated_at DESC);